export type PixelIconName = keyof typeof GRIDS;

/** Convierte una rejilla en dos trazos SVG (trazo y relleno) uniendo píxeles por fila. */
function gridToPaths(grid: readonly string[]): { ink: string; fill: string } {
  let ink = "";
  let fill = "";
  grid.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const ch = row[x];
      if (ch === "#" || ch === "o") {
        let w = 1;
        while (x + w < 16 && row[x + w] === ch) w++;
        const seg = `M${x} ${y}h${w}v1h-${w}z`;
        if (ch === "#") ink += seg;
        else fill += seg;
        x += w;
      } else {
        x++;
      }
    }
  });
  return { ink, fill };
}

const PATHS = Object.fromEntries(
  Object.entries(GRIDS).map(([name, grid]) => [name, gridToPaths(grid)]),
) as Record<PixelIconName, { ink: string; fill: string }>;

interface PixelIconProps {
  name: PixelIconName;
  className?: string;
  /** Texto accesible. Si se omite, el icono es decorativo. */
  title?: string;
}

export function PixelIcon({ name, className, title }: PixelIconProps) {
  const p = PATHS[name];
  return (
    <svg
      viewBox="0 0 16 16"
      className={className}
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      focusable="false"
    >
      {p.fill && <path d={p.fill} opacity={0.36} />}
      <path d={p.ink} />
    </svg>
  );
}
